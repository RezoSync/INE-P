import { expect, test } from "@playwright/test"

test("recorrido con datos locales del INE, estados pendientes y descarga", async ({ page, baseURL }) => {
  const externalRequests: string[] = []
  const consoleErrors: string[] = []
  await page.setViewportSize({ width: 1440, height: 1000 })
  page.on("request", (request) => {
    if (!request.url().startsWith(baseURL ?? "")) externalRequests.push(request.url())
  })
  page.on("pageerror", (error) => consoleErrors.push(error.message))
  page.on("console", (message) => {
    if (message.type() === "error") consoleErrors.push(message.text())
  })

  await page.goto("/")
  await expect(page.getByRole("heading", { level: 1 })).toContainText("15 años")
  await expect(page.getByText("Participación nacional · 2024")).toBeVisible()
  await expect(page.locator(".hero-stat")).toContainText("59.7 %")
  await expect(page.locator(".hero-stat")).toContainText("Oficial · INE")
  await expect(page.locator(".hero-stat")).toContainText("45.46 años")
  await expect(page.locator(".hero-summary")).toContainText("54.9 millones de personas")
  await expect(page.locator(".hero-summary")).toContainText("cerca de 6 de cada 10")
  await page.locator(".site-preferences summary").click()
  const defaultNavFontSize = Number(
    (await page.locator(".nav-links").evaluate((element) => getComputedStyle(element).fontSize)).replace("px", ""),
  )
  await page.locator("#text-size").selectOption("largest")
  await expect(page.locator("html")).toHaveAttribute("data-text-size", "largest")
  await expect(page.locator("html")).toHaveCSS("--text-scale", "1.2")
  const enlargedNavFontSize = Number(
    (await page.locator(".nav-links").evaluate((element) => getComputedStyle(element).fontSize)).replace("px", ""),
  )
  expect(enlargedNavFontSize).toBeGreaterThan(defaultNavFontSize)
  await page.getByRole("button", { name: "Usar modo oscuro" }).click()
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark")
  expect(await page.evaluate(() => localStorage.getItem("ine-voto-theme"))).toBe("dark")
  expect(await page.evaluate(() => localStorage.getItem("ine-voto-text-size"))).toBe("largest")
  await expect(page.locator("html")).toHaveCSS("color-scheme", "dark")
  await page.reload()
  await expect(page.locator("html")).toHaveAttribute("data-theme", "dark")
  await expect(page.locator("html")).toHaveAttribute("data-text-size", "largest")
  await page.locator(".site-preferences summary").click()
  await page.getByRole("button", { name: "Usar modo claro" }).click()
  await page.locator("#text-size").selectOption("normal")
  await page.reload()
  await expect(page.locator("html")).toHaveAttribute("data-theme", "light")
  await expect(page.locator("html")).toHaveAttribute("data-text-size", "normal")
  await page.getByRole("link", { name: "¿Qué tan distintas son las entidades?" }).click()
  await expect(page).toHaveURL(/#cuartiles$/)
  await expect(page.getByRole("heading", { name: "Cuartiles estatales" })).toBeVisible()

  const glossaryListNominal = page.locator(".glossary-item").filter({ has: page.getByText("Lista nominal", { exact: true }) })
  await glossaryListNominal.locator("summary").focus()
  await glossaryListNominal.locator("summary").press("Enter")
  await expect(glossaryListNominal.getByRole("tooltip")).toContainText("no se usa como denominador")
  await glossaryListNominal.locator("summary").press("Enter")
  await expect(glossaryListNominal.getByRole("tooltip")).toBeHidden()
  await expect(page.getByText("Participación", { exact: true })).toBeVisible()

  await page.getByRole("link", { name: "Historia", exact: true }).click()
  await expect(page.getByRole("link", { name: "Historia", exact: true })).toHaveAttribute("aria-current", "location")
  await expect(page.getByRole("heading", { name: /Cada elección cuenta/ })).toBeVisible()
  await expect(page.getByRole("heading", { name: "Elecciones presidenciales" })).toBeVisible()
  await expect(page.getByRole("heading", { name: "Elecciones intermedias" })).toBeVisible()
  await expect(page.locator(".timeline li")).toHaveCount(6)
  await expect(page.locator(".history-insight")).toContainText("más alta")
  await expect(page.locator(".series-card .chart-note")).toHaveCount(2)
  await expect(page.locator(".quartile-section .chart-note")).toContainText("No identifica qué entidad")
  await expect(page.getByRole("heading", { name: "Cuartiles estatales" })).toBeVisible()

  await page.locator("#entity-search").fill("Baja California Sur")
  await page.locator("#entity-select").selectOption("BCS")
  await expect(page.locator("#entity-select")).toHaveValue("BCS")
  await expect(page.locator(".state-card")).toContainText("Baja California Sur")
  await expect(page.locator(".state-card")).toContainText("53.1 %")
  await expect(page.locator(".state-card")).toContainText(/dato pendiente/i)
  await expect(page.locator(".state-card")).toContainText("Promedio nacional")
  await expect(page.locator(".state-card")).toContainText("Mediana estatal")
  await page.locator("#compare-entity-select").selectOption("YUC")
  await expect(page.locator(".entity-comparison-grid")).toContainText("Baja California Sur")
  await expect(page.locator(".entity-comparison-grid")).toContainText("Yucatán")
  await page.getByRole("button", { name: "Mayor participación: Yucatán, 71.4 %" }).click()
  await expect(page.locator("#entity-select")).toHaveValue("YUC")
  await page.locator("#entity-search").fill("Baja California Sur")
  await page.locator("#entity-select").selectOption("BCS")
  await expect(page.locator(".map-legend")).toContainText("47.0")
  await expect(page.locator(".map-legend")).toContainText("71.4")
  const mapTransformBeforeZoom = await page.locator(".mexico-map g").getAttribute("transform")
  await page.getByRole("button", { name: "Acercar mapa" }).click()
  await expect(page.locator(".map-zoom-controls")).toContainText("150 %")
  await expect(page.locator(".mexico-map g")).not.toHaveAttribute("transform", mapTransformBeforeZoom ?? "")
  await page.getByRole("button", { name: "Restablecer acercamiento del mapa" }).click()
  await expect(page.locator(".map-zoom-controls")).toContainText("100 %")

  await page.getByRole("button", { name: "Tabla", exact: true }).click()
  await expect(page.getByRole("table", { name: /Participación por entidad/ })).toBeVisible()
  await page.getByRole("button", { name: "Baja California", exact: true }).click()
  await expect(page.locator("#entity-select")).toHaveValue("BC")
  await page.getByRole("button", { name: "Mapa", exact: true }).click()
  await expect(page.locator(".mexico-map path")).toHaveCount(32)
  const yucatanMapPath = page.getByRole("button", { name: "Yucatán: 71.4 %" })
  await yucatanMapPath.click({ force: true })
  await expect(page.locator("#entity-select")).toHaveValue("YUC")
  await expect(page.locator('.mexico-map path[data-entity-code="YUC"]')).toHaveAttribute("stroke", "var(--magenta)")
  const bajaCaliforniaPath = page.locator('.mexico-map path[data-entity-code="BC"]')
  await bajaCaliforniaPath.hover({ force: true })
  await expect(bajaCaliforniaPath).toHaveAttribute("stroke", "var(--magenta)")
  await page.locator("body").hover()
  await expect(bajaCaliforniaPath).toHaveAttribute("stroke", "var(--map-outline)")
  const bajaCaliforniaSurPath = page.locator('.mexico-map path[data-entity-code="BCS"]')
  await bajaCaliforniaSurPath.focus()
  await bajaCaliforniaSurPath.press("Enter")
  await expect(page.locator("#entity-select")).toHaveValue("BCS")
  await expect(bajaCaliforniaSurPath).toHaveAttribute("stroke", "var(--magenta)")

  await page.getByRole("button", { name: "Intermedias" }).click()
  await expect(page.locator("#election-year-select")).toHaveValue("2021")
  await expect(page.locator(".participation-ranking")).toContainText("Dato pendiente")
  await expect(page.locator(".state-card")).toContainText("La fuente disponible no incluye la participación estatal de 2021")
  await expect(page.locator(".mexico-map path[data-entity-code=\"YUC\"]")).toHaveAttribute("aria-label", "Yucatán: Dato pendiente")
  await page.getByRole("button", { name: "Presidenciales" }).click()
  await expect(page.locator("#election-year-select")).toHaveValue("2024")
  await expect(page.locator(".state-card")).toContainText("53.1 %")

  await page.getByRole("tab", { name: "Etapa de vida" }).click()
  await expect(page.getByRole("tabpanel")).toContainText("Composición de votantes")
  await expect(page.getByRole("tabpanel").locator(".composition-row")).toHaveCount(6)
  await page.getByRole("button", { name: "Ver tabla" }).click()
  await expect(page.getByRole("table", { name: /Composición porcentual/ })).toBeVisible()
  await expect(page.getByRole("tabpanel")).not.toContainText("diferencias entre elecciones")
  await page.getByRole("tab", { name: "Tipo de sección" }).click()
  await expect(page.getByRole("tabpanel").locator(".composition-row")).toHaveCount(6)
  await expect(page.getByRole("heading", { name: "Edad promedio de los votantes" })).toBeVisible()
  await expect(page.getByRole("heading", { name: "Tasa de participación por edad" })).toBeVisible()
  await expect(page.getByRole("heading", { name: "Tasa de participación por sexo" })).toBeVisible()
  await expect(page.getByRole("heading", { name: "Tasa de participación por tipo de sección" })).toBeVisible()
  await expect(page.locator(".pending-dimension .pending small")).toHaveCount(3)
  await expect(page.locator(".pending-dimension .pending small").first()).toContainText("no ofrece la tasa de participación por edad")

  const downloadPromise = page.waitForEvent("download")
  await page.getByRole("button", { name: "Descargar PNG", exact: true }).click()
  const download = await downloadPromise
  expect(download.suggestedFilename()).toMatch(/15-anos-de-tu-voto-BCS\.png/)

  await page.setViewportSize({ width: 1024, height: 900 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(1024)
  await page.setViewportSize({ width: 375, height: 812 })
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(375)
  await expect(page.getByText("Participación por estado solo disponible para 2024 en esta versión.")).toBeVisible()
  await expect(page.locator(".navbar")).toHaveCSS("position", "fixed")
  await page.evaluate(() => window.scrollTo(0, document.body.scrollHeight))
  await expect(page.getByRole("button", { name: "Volver arriba" })).toBeVisible()
  await page.getByRole("button", { name: "Volver arriba" }).click()
  await expect(page.getByRole("button", { name: "Volver arriba" })).toBeHidden()
  await page.locator(".site-preferences summary").click()
  await expect(page.getByRole("button", { name: "Usar modo oscuro" })).toBeVisible()
  const glossaryParticipation = page.locator(".glossary-item").filter({ has: page.getByText("Participación", { exact: true }) })
  await glossaryParticipation.locator("summary").click()
  await expect(glossaryParticipation.getByRole("tooltip")).toContainText("sí votaron")
  expect(externalRequests).toEqual([])
  expect(consoleErrors).toEqual([])
})
